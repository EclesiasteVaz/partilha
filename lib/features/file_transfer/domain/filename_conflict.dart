/// Deterministic filename conflict resolution (`FEATURES.md` §26,
/// `features/file_transfer/FEATURE.md` §12, §19).
///
/// Returns the first free name in the documented sequence:
///
/// ```text
/// photo.jpg → photo (1).jpg → photo (2).jpg
/// ```
///
/// The caller supplies [exists], so the rule never touches a filesystem
/// itself: it stays pure domain logic that is testable without I/O and
/// reusable unchanged by the receiver that will write the bytes
/// (`AGENTS.md` §5, §42).
///
/// Never overwrites — the sequence only ever moves away from a name that is
/// already taken, including names that were themselves generated by an
/// earlier conflict (`photo (1).jpg` taken → `photo (2).jpg`).
///
/// [exists] must answer for a consistent view of the destination while the
/// loop runs. Deciding the name and creating the file are separate steps: the
/// writer must still open exclusively, because no naming rule can close the
/// gap between checking and creating on a filesystem another program can also
/// write to (`AGENTS.md` §29).
String resolveFilenameConflict(
  String desiredName,
  bool Function(String candidate) exists,
) {
  if (!exists(desiredName)) return desiredName;

  final (String base, String extension) = _split(desiredName);
  for (int suffix = 1; ; suffix++) {
    final String candidate = '$base ($suffix)$extension';
    if (!exists(candidate)) return candidate;
  }
}

/// Splits [name] into the part before the last dot and the extension itself.
///
/// A dot at position `0` starts a hidden name rather than an extension, so
/// `.env` has none. The split happens before the *last* dot only — the same
/// place mainstream file managers insert the suffix — so `archive.tar.gz`
/// becomes `archive.tar (1).gz`, preserving every part the user typed.
(String, String) _split(String name) {
  final int dot = name.lastIndexOf('.');
  if (dot <= 0) return (name, '');
  return (name.substring(0, dot), name.substring(dot));
}
